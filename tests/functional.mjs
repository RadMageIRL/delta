// Functional checks: typing and comparing, keyboard shortcuts and Tab order, taps on a touch
// screen, Share Link from generation to loading, theme persistence, and Folder Compare on two
// fixture folders, with no console errors and no requests to other sites.
//
//   node tests/functional.mjs <delta-url>
import { pathToFileURL } from 'node:url';
import { launch, reporter, sleep } from './lib/chrome.mjs';
import { SWITCH, click, compareFixtureFolders, isActive, setPair } from './lib/delta.mjs';

async function key(b, k, { ctrl = false, shift = false } = {}) {
  const modifiers = (ctrl ? 2 : 0) | (shift ? 8 : 0);
  const named = { Enter: { code: 'Enter', windowsVirtualKeyCode: 13, text: '\r' }, Escape: { code: 'Escape', windowsVirtualKeyCode: 27 }, Tab: { code: 'Tab', windowsVirtualKeyCode: 9 } }[k];
  const p = named ? { key: k, ...named } : { key: k, text: k, code: '', windowsVirtualKeyCode: k.toUpperCase().charCodeAt(0) };
  if (ctrl) delete p.text;
  await b.send('Input.dispatchKeyEvent', { type: p.text ? 'keyDown' : 'rawKeyDown', modifiers, ...p });
  await b.send('Input.dispatchKeyEvent', { type: 'keyUp', modifiers, ...p });
  await sleep(120);
}

async function tap(b, selector) {
  const r = await b.eval(`const el = document.querySelector(${JSON.stringify(selector)}); el.scrollIntoView({ block: 'center' }); const r = el.getBoundingClientRect(); return { x: r.left + r.width / 2, y: r.top + r.height / 2 }`);
  await sleep(150);
  await b.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: r.x, y: r.y }] });
  await b.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  await sleep(350);
}

export async function run(url, { label = 'functional' } = {}) {
  const rep = reporter(label);
  const check = rep.check;

  // Desktop: typing, compare, keyboard.
  {
    const b = await launch({ width: 1400, height: 1000 });
    await b.goto(url);
    await b.eval(`document.getElementById('text-a').focus(); return 1`);
    await b.send('Input.insertText', { text: SWITCH.before });
    await b.eval(`document.getElementById('text-b').focus(); return 1`);
    await b.send('Input.insertText', { text: SWITCH.after });
    await key(b, 'Enter', { ctrl: true });
    await sleep(400);
    const stats = await b.eval(`return document.getElementById('diff-stats').textContent.replace(/\\s+/g, ' ').trim()`);
    check('typed text compares with Ctrl+Enter', /\+8\b/.test(stats) && /-2\b|\u22122\b/.test(stats) && /5 changes/.test(stats), stats);
    const rows = await b.eval(`return { del: document.querySelectorAll('#diff-output .diff-half.del').length, add: document.querySelectorAll('#diff-output .diff-half.add').length, words: document.querySelectorAll('#diff-output .diff-word-add').length }`);
    check('diff shows removed, added and word-level changes', rows.del >= 2 && rows.add >= 8 && rows.words >= 1, JSON.stringify(rows));
    await b.eval(`document.activeElement.blur(); return 1`);
    await key(b, ']');
    check('] selects the next change', await b.eval(`return document.querySelectorAll('.hunk-flash').length > 0`));
    await key(b, '?');
    check('? opens the About dialog', await b.eval(`return document.getElementById('about-dialog').open`));
    await key(b, 'Escape');
    check('Escape closes it', await b.eval(`return !document.getElementById('about-dialog').open`));
    // Undo after typing.
    await b.eval(`document.getElementById('text-a').focus(); return 1`);
    await b.send('Input.insertText', { text: 'extra line\n' });
    await b.eval(`document.activeElement.blur(); return 1`);
    await key(b, 'z', { ctrl: true });
    check('Ctrl+Z undoes typing', await b.eval(`return !document.getElementById('text-a').value.includes('extra line')`));
    // Tab walks the controls in page order without getting stuck.
    await b.eval(`window.scrollTo(0, 0); document.activeElement && document.activeElement.blur(); document.body.focus(); return 1`);
    const order = [];
    for (let i = 0; i < 90; i++) { await key(b, 'Tab'); order.push(await b.eval(`const e = document.activeElement; return e ? (e.id || e.dataset.appMode || e.dataset.view || e.textContent.trim().slice(0, 12)) : ''`)); }
    for (const id of ['theme-toggle', 'about-button', 'folder', 'opt-preview', 'base-toggle', 'text-a'])
      check(`Tab reaches ${id}`, order.includes(id), order.join(' > '));
    check('Tab moves on each press', new Set(order).size > 30, `${new Set(order).size} distinct`);

    // Share Link: generated by the page (compressed when the browser can), then opened.
    await setPair(b, 'alpha\nbeta_gamma\n' + '*'.repeat(30) + '\n', 'alpha\nbeta_delta\n', { compare: true });
    await b.eval(`window.__copied = null; navigator.clipboard.writeText = (t) => { window.__copied = t; return Promise.resolve(); }; document.getElementById('share-button').click(); await new Promise((r) => setTimeout(r, 500)); return 1`);
    const link = await b.eval('return window.__copied');
    check('Share Link copies a link to this page with the comparison after #', typeof link === 'string' && link.startsWith(url.split('#')[0]) && /#d=[jz]:/.test(link), String(link).slice(0, 80));
    await b.eval(`localStorage.clear(); return 1`);
    await b.goto('about:blank', { settle: 100 });
    await b.goto(link, { settle: 1200 });
    const back = await b.eval(`return { a: document.getElementById('text-a').value, b: document.getElementById('text-b').value }`);
    check('the copied link opens the same comparison', back.a === 'alpha\nbeta_gamma\n' + '*'.repeat(30) + '\n' && back.b === 'alpha\nbeta_delta\n', JSON.stringify(back).slice(0, 120));

    // Theme persists across a reload.
    await b.goto('about:blank', { settle: 100 });
    await b.goto(url);
    await click(b, 'theme-toggle'); await click(b, 'theme-toggle');
    const chosen = await b.eval(`return document.documentElement.getAttribute('data-theme')`);
    await b.goto(url);
    check('chosen theme survives a reload', chosen && await b.eval(`return document.documentElement.getAttribute('data-theme')`) === chosen, chosen);
    await b.eval(`localStorage.clear(); return 1`);

    // Folder Compare on the two fixture folders (see compareFixtureFolders for how).
    await b.goto(url);
    await compareFixtureFolders(b);
    const ra = await b.eval(`return document.getElementById('folder-info-a').textContent.replace(/\\s+/g, ' ').trim()`), rb = '';
    const fc =await b.eval(`return { rows: [...document.querySelectorAll('.folder-diff-row')].map((r) => r.dataset.status + ' ' + r.querySelector('.folder-diff-row-path').textContent), summary: document.getElementById('folder-diff-summary').textContent.replace(/\\s+/g, ' ').trim() }`);
    const statuses = fc.rows.map((r) => r.split(' ')[0]).sort().join(',');
    check('Folder Compare lists added, removed, modified and unchanged files', statuses === 'added,modified,modified,removed,unchanged', `picks ${ra}/${rb}; ${JSON.stringify(fc)}`);
    // Open the modified image row: the pixel-difference overlay uses blob: images.
    await b.eval(`const row = [...document.querySelectorAll('.folder-diff-row')].find((r) => r.textContent.includes('rack_diagram')); row && row.click(); await new Promise((r) => setTimeout(r, 1200)); return 1`);
    const img = await b.eval(`const a = document.getElementById('fd-img-a'); return a ? { loaded: a.complete && a.naturalWidth > 0, src: a.src.slice(0, 5) } : null`);
    check('a modified image opens side by side from blob: URLs', img && img.loaded && img.src === 'blob:', JSON.stringify(img));
    check('desktop: no page errors', b.errors.length === 0, b.errors.slice(0, 3).join(' | '));
    check('desktop: no requests to other sites', b.outside.length === 0, b.outside.slice(0, 5).join(', '));
    await b.close();
  }

  // Phone: taps on a touch screen at 390 px.
  {
    const b = await launch({ width: 390, height: 844, mobile: true, touch: true });
    await b.goto(url);
    await setPair(b, SWITCH.before, SWITCH.after, { compare: false });
    await tap(b, '#compare-button');
    check('tap: Compare runs the diff', await b.eval(`return document.querySelectorAll('#diff-output .diff-half.add').length > 0`));
    await tap(b, '#opt-preview');
    check('tap: Preview toggles on', await isActive(b, 'opt-preview'));
    await tap(b, '#opt-preview');
    await tap(b, '[data-view="unified"]');
    check('tap: Unified view', await b.eval(`return document.querySelector('[data-view="unified"]').classList.contains('active')`));
    await tap(b, '[data-view="split"]');
    await tap(b, '#about-button');
    check('tap: About opens', await b.eval(`return document.getElementById('about-dialog').open`));
    await tap(b, '#about-close-button');
    check('tap: About closes', await b.eval(`return !document.getElementById('about-dialog').open`));
    await tap(b, '#text-a');
    check('tap: the editor takes focus for typing', await b.eval(`return document.activeElement.id === 'text-a'`));
    await b.send('Input.insertText', { text: 'typed on a phone\n' });
    check('typing on a phone reaches the editor', await b.eval(`return document.getElementById('text-a').value.includes('typed on a phone')`));
    const zoom = await b.eval(`return { scale: visualViewport.scale, scrollWidth: document.documentElement.scrollWidth }`);
    check('phone: page stays at 100% and screen width while typing', zoom.scale === 1 && zoom.scrollWidth <= 390, JSON.stringify(zoom));
    check('phone: no page errors', b.errors.length === 0, b.errors.slice(0, 3).join(' | '));
    check('phone: no requests to other sites', b.outside.length === 0, b.outside.slice(0, 5).join(', '));
    await b.close();
  }
  return { results: rep.results };
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const { results } = await run(process.argv[2]);
  const failed = results.filter((r) => !r.ok).length;
  console.log(`functional: ${results.length - failed} passed, ${failed} failed`);
  process.exit(failed ? 1 : 0);
}
